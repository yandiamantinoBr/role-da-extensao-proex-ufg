import assert from 'node:assert/strict';
import test from 'node:test';
import { compile, teamScenario, teamsWorkspace } from './support/work-teams-fixture.mjs';

const { prepareTeamExport, teamExportDocument } = await import(compile('components/portal/work-teams-export.ts'));

async function testExport(t) {
  const f = await teamScenario(t);
  const read = async () => teamsWorkspace(f.db, await f.actor('viewer-a'), {
    organizationId: 'org-a', projectId: 'project-a', teamId: f.a, status: 'open',
  }, true);
  return { ...f, read };
}

test('the team export projects the selected state with no names from the roster or a second project', async t => {
  const { read } = await testExport(t);
  const document = await prepareTeamExport(read, async fresh => teamExportDocument(fresh, 'open'), () => {});
  assert.deepEqual(document.rows, [{
    title: 'Conferir materiais do evento', project_name: 'Projeto Aurora', status: 'Aberta',
    priority: 'Alta', due_at: '01/01/2020',
  }]);
  assert.equal(document.title, 'Demandas · Comunicação e Design');
  assert.deepEqual(document.metrics.map(metric => metric.value), [1, 1]);
  assert.doesNotMatch(JSON.stringify(document), /Horizonte|viewer-a|other-a2|Artes prontas/);
});

test('revocation after generating the bytes denies delivery through the real authorization service', async t => {
  const f = await testExport(t);
  let artifact, reads = 0;
  const read = () => { reads++; return f.read(); };
  await assert.rejects(prepareTeamExport(read, async fresh => {
    assert.equal(fresh.tasks.length, 1);
    artifact = new Blob(['Generated bytes']);
    f.native.prepare("UPDATE members SET revoked_at=? WHERE user_id='viewer-a' AND project_id='project-a'").run(new Date().toISOString());
    return artifact;
  }, () => {}), {status: 403});
  assert.equal(reads, 2);
  assert.ok(artifact.size > 0, 'the format was already generated when access was revoked');
});

test('an edited or moved demand during generation blocks delivery and abort skips the last read', async t => {
  const f = await testExport(t);
  await assert.rejects(prepareTeamExport(f.read, async () => {
    f.native.prepare('UPDATE followup_tasks SET title=? WHERE id=?').run('Título atualizado em outra sessão', f.shared);
    return new Blob(['Generated bytes']);
  }, () => {}), {status: 409});
  const controller = new AbortController();
  let reads = 0;
  await assert.rejects(prepareTeamExport(() => { reads++; return f.read(); }, async () => {
    controller.abort();
    return new Blob(['Generated bytes']);
  }, () => controller.signal.throwIfAborted()), {name: 'AbortError'});
  assert.equal(reads, 1);
});
